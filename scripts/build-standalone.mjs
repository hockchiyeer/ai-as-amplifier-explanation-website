#!/usr/bin/env node
/**
 * npm run build:standalone
 *
 * Rebuilds the zero-build, double-click-to-open version of the site:
 *
 *   1. Builds a fresh React bundle with Vite (vite.standalone.config.ts) into ONE self-contained index.html.
 *   2. Extracts the latest dictionary (EN / 中文 / BM) from client/src/lib/i18n.ts into content.js
 *      (`window.AI_AMPLIFIER_CONTENT = {...}` — editable, no rebuild needed to change wording).
 *   3. Copies the newly built index.html, content.js and resources/ into BOTH
 *        - the project root directory, and
 *        - the AI_Amplifier_Standalone/ distribution folder.
 *
 * Options
 *   --full   also copy resources/data/pptx_images (generated PPTX images used only by the Express server;
 *            the static page never reads them, so they are skipped by default to keep the folder small).
 *   --help   show this text.
 */
import { build } from 'vite';
import { build as esbuild } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '..');
const CLIENT_SRC = path.join(ROOT, 'client', 'src');
const VITE_OUT = path.join(ROOT, 'dist', 'standalone');
const DIST_DIR = path.join(ROOT, 'AI_Amplifier_Standalone');
const RESOURCES = path.join(ROOT, 'resources');

/** Load client/src/lib/i18n.ts and return the full dictionary `{ en, zh, ms }`. */
export async function extractContent() {
  const result = await esbuild({
    entryPoints: [path.join(CLIENT_SRC, 'lib', 'i18n.ts')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'node',
    logLevel: 'silent',
    alias: { '@': CLIENT_SRC },
  });
  const mod = { exports: {} };
  new Function('module', 'exports', result.outputFiles[0].text)(mod, mod.exports);
  const dict = mod.exports.i18n;
  if (!dict || !dict.en || !dict.zh || !dict.ms) throw new Error('Could not read en/zh/ms from client/src/lib/i18n.ts');
  // plain JSON data only (also drops anything that cannot be edited as text)
  return JSON.parse(JSON.stringify({ en: dict.en, zh: dict.zh, ms: dict.ms }));
}

export function renderContentJs(dict) {
  return (
    '/* AI Amplifier — site content (EN / 中文 / BM)\n' +
    ' * Generated by `npm run build:standalone` from client/src/lib/i18n.ts.\n' +
    ' * index.html loads this file first. Any text edited here overrides the built-in wording, so you can change\n' +
    ' * the site by editing this file only (keep the structure and the URLs; edit the text values).\n' +
    ' * Re-running the build regenerates it from i18n.ts and overwrites manual edits. */\n' +
    'window.AI_AMPLIFIER_CONTENT = ' +
    JSON.stringify(dict, null, 2) +
    ';\n'
  );
}

function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}

function copyDir(src, dest, filter) {
  fs.cpSync(src, dest, { recursive: true, filter });
}

export async function main(argv = process.argv.slice(2)) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(fs.readFileSync(import.meta.filename, 'utf8').split('*/')[0].replace(/^#!.*\n/, ''));
    return;
  }
  const full = argv.includes('--full');
  const step = (n, msg) => console.log(`\n[${n}/4] ${msg}`);

  step(1, 'Building the standalone React bundle with Vite …');
  await build({ configFile: path.join(ROOT, 'vite.standalone.config.ts'), logLevel: 'warn' });
  const builtHtml = path.join(VITE_OUT, 'index.html');
  if (!fs.existsSync(builtHtml)) throw new Error(`Vite did not produce ${builtHtml}`);

  step(2, 'Extracting the dictionary from client/src/lib/i18n.ts → content.js …');
  const contentJs = renderContentJs(await extractContent());
  fs.writeFileSync(path.join(VITE_OUT, 'content.js'), contentJs);

  step(3, 'Syncing slide screenshots into resources/slides …');
  const slidesSrc = path.join(ROOT, 'client', 'public', 'slides');
  rmrf(path.join(RESOURCES, 'slides'));
  copyDir(slidesSrc, path.join(RESOURCES, 'slides'));

  step(4, 'Copying index.html, content.js and resources/ into the root and AI_Amplifier_Standalone/ …');
  for (const f of ['index.html', 'content.js']) {
    fs.copyFileSync(path.join(VITE_OUT, f), path.join(ROOT, f));
  }
  rmrf(DIST_DIR);
  fs.mkdirSync(DIST_DIR, { recursive: true });
  for (const f of ['index.html', 'content.js']) {
    fs.copyFileSync(path.join(VITE_OUT, f), path.join(DIST_DIR, f));
  }
  const skipImages = path.join(RESOURCES, 'data', 'pptx_images');
  copyDir(RESOURCES, path.join(DIST_DIR, 'resources'), src => full || !(src === skipImages || src.startsWith(skipImages + path.sep)));

  const kb = p => `${Math.round(fs.statSync(p).size / 1024)} KB`;
  console.log('\nDone.');
  console.log(`  ${path.join(ROOT, 'index.html')}  (${kb(path.join(ROOT, 'index.html'))})`);
  console.log(`  ${path.join(ROOT, 'content.js')}  (${kb(path.join(ROOT, 'content.js'))})`);
  console.log(`  ${DIST_DIR}${path.sep}  (index.html, content.js, resources/)`);
  console.log('Open index.html (root or AI_Amplifier_Standalone/) directly in a browser — no server needed.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(err => {
    console.error('\nbuild:standalone failed:\n', err);
    process.exit(1);
  });
}
